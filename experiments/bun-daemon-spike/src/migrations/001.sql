CREATE TABLE IF NOT EXISTS migrations (version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS tasks (
  id TEXT PRIMARY KEY, request_id TEXT NOT NULL UNIQUE, fingerprint TEXT NOT NULL,
  input TEXT NOT NULL, state TEXT NOT NULL, pid INTEGER, exit_code INTEGER,
  created INTEGER NOT NULL, not_before INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS outbox (
  task_id TEXT PRIMARY KEY REFERENCES tasks(id), terminal TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0, delivered INTEGER NOT NULL DEFAULT 0
);
